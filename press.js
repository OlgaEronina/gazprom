  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;", "'": "&#39;" }[c];
    });
  }

  function pageList(total, current) {
    if (total <= 7) {
      var all = [];
      for (var i = 1; i <= total; i++) all.push(i);
      return all;
    }
    var out = [1];
    if (current > 3) out.push("…");
    for (var p = Math.max(2, current - 1); p <= Math.min(total - 1, current + 1); p++) out.push(p);
    if (current < total - 2) out.push("…");
    out.push(total);
    return out;
  }

  function renderPagination(el, total, current, go) {
    if (!el) return;
    if (total <= 1) {
      el.innerHTML = "";
      el.hidden = true;
      return;
    }
    el.hidden = false;
    var html = '<button class="pc-pag__arrow" type="button" data-page="' + (current - 1) + '"' +
      (current === 1 ? " disabled" : "") + ' aria-label="Предыдущая страница"><span class="pc-pag__icon pc-pag__icon--prev" aria-hidden="true"></span></button>';
    pageList(total, current).forEach(function (p) {
      if (p === "…") {
        html += '<span class="pc-pag__dots" aria-hidden="true">…</span>';
      } else {
        html += '<button class="pc-pag__item' + (p === current ? " is-active" : "") + '" type="button" data-page="' + p +
          '"' + (p === current ? ' aria-current="page"' : "") + ' aria-label="Страница ' + p + '">' + p + "</button>";
      }
    });
    html += '<button class="pc-pag__arrow" type="button" data-page="' + (current + 1) + '"' +
      (current === total ? " disabled" : "") + ' aria-label="Следующая страница"><span class="pc-pag__icon pc-pag__icon--next" aria-hidden="true"></span></button>';
    el.innerHTML = html;
    el.onclick = function (e) {
      var btn = e.target.closest("button[data-page]");
      if (!btn || btn.disabled) return;
      go(parseInt(btn.getAttribute("data-page"), 10));
    };
  }

  function Paged(listEl, pagEl, size, renderItem, onDraw) {
    var items = [];
    var page = 1;
    function draw() {
      var total = Math.max(1, Math.ceil(items.length / size));
      page = Math.min(Math.max(1, page), total);
      listEl.innerHTML = items.slice((page - 1) * size, page * size).map(renderItem).join("");
      renderPagination(pagEl, total, page, function (n) {
        page = n;
        draw();
        listEl.scrollIntoView({ behavior: "smooth", block: "start" });
      });
      if (onDraw) onDraw(items.length);
    }
    return {
      set: function (list) { items = list; page = 1; draw(); },
      draw: draw
    };
  }

